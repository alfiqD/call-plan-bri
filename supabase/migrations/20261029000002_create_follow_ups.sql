-- ==============================================================================
-- MIGRATION: Follow-up Reminder & Riwayat Tindak Lanjut
-- Tabel, Relasi, Indeks, dan Kebijakan Row Level Security (RLS)
-- ==============================================================================

-- 1. Buat Tabel public.follow_ups
CREATE TABLE IF NOT EXISTS public.follow_ups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nasabah_id BIGINT NOT NULL REFERENCES public.nasabahs(id) ON DELETE CASCADE,
    jadwal_kunjungan_id BIGINT REFERENCES public.jadwal_kunjungans(id) ON DELETE SET NULL,
    rm_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    tanggal_follow_up DATE NOT NULL,
    waktu_follow_up TIME NOT NULL DEFAULT '09:00:00',
    jenis_tindak_lanjut VARCHAR(50) NOT NULL CHECK (
        jenis_tindak_lanjut IN (
            'Telepon',
            'WhatsApp',
            'Pertemuan/Kunjungan Ulang',
            'Melengkapi Dokumen',
            'Penawaran Produk',
            'Lainnya'
        )
    ),
    catatan TEXT NOT NULL,
    prioritas VARCHAR(20) NOT NULL DEFAULT 'Normal' CHECK (
        prioritas IN ('Rendah', 'Normal', 'Tinggi')
    ),
    status VARCHAR(30) NOT NULL DEFAULT 'Belum Dilakukan' CHECK (
        status IN ('Belum Dilakukan', 'Selesai', 'Dibatalkan')
    ),
    hasil_tindak_lanjut TEXT,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Komentar Tabel dan Kolom
COMMENT ON TABLE public.follow_ups IS 'Agenda reminder dan riwayat tindak lanjut nasabah pasca-kunjungan untuk RM dan pemantauan Admin';
COMMENT ON COLUMN public.follow_ups.nasabah_id IS 'ID nasabah target tindak lanjut';
COMMENT ON COLUMN public.follow_ups.jadwal_kunjungan_id IS 'Referensi ke jadwal kunjungan asal (jika tindak lanjut berawal dari kunjungan)';
COMMENT ON COLUMN public.follow_ups.rm_id IS 'Pemilik tugas tindak lanjut (RM penanggung jawab)';
COMMENT ON COLUMN public.follow_ups.status IS 'Status tindak lanjut: Belum Dilakukan, Selesai, Dibatalkan';

-- 3. Indeks Performa
CREATE INDEX IF NOT EXISTS idx_follow_ups_rm_id ON public.follow_ups(rm_id);
CREATE INDEX IF NOT EXISTS idx_follow_ups_nasabah_id ON public.follow_ups(nasabah_id);
CREATE INDEX IF NOT EXISTS idx_follow_ups_jadwal_id ON public.follow_ups(jadwal_kunjungan_id);
CREATE INDEX IF NOT EXISTS idx_follow_ups_tanggal ON public.follow_ups(tanggal_follow_up);
CREATE INDEX IF NOT EXISTS idx_follow_ups_status ON public.follow_ups(status);

-- 4. Aktifkan Row Level Security (RLS)
ALTER TABLE public.follow_ups ENABLE ROW LEVEL SECURITY;

-- 5. Kebijakan RLS (Row Level Security)
-- RM hanya dapat melihat miliknya sendiri; Admin dapat memantau seluruh follow-up
DROP POLICY IF EXISTS "follow_ups_select_policy" ON public.follow_ups;
CREATE POLICY "follow_ups_select_policy" ON public.follow_ups
    FOR SELECT
    TO authenticated
    USING (
        public.is_user_approved() AND
        (rm_id = auth.uid() OR public.current_user_role() = 'admin')
    );

-- RM dapat membuat follow-up untuk diri sendiri; Admin dapat menugaskan ke RM mana pun
DROP POLICY IF EXISTS "follow_ups_insert_policy" ON public.follow_ups;
CREATE POLICY "follow_ups_insert_policy" ON public.follow_ups
    FOR INSERT
    TO authenticated
    WITH CHECK (
        public.is_user_approved() AND
        (rm_id = auth.uid() OR public.current_user_role() = 'admin')
    );

-- RM hanya dapat memperbarui follow-up miliknya; Admin dapat memperbarui semua
DROP POLICY IF EXISTS "follow_ups_update_policy" ON public.follow_ups;
CREATE POLICY "follow_ups_update_policy" ON public.follow_ups
    FOR UPDATE
    TO authenticated
    USING (
        public.is_user_approved() AND
        (rm_id = auth.uid() OR public.current_user_role() = 'admin')
    )
    WITH CHECK (
        public.is_user_approved() AND
        (rm_id = auth.uid() OR public.current_user_role() = 'admin')
    );

-- RM dapat menghapus follow-up miliknya; Admin dapat menghapus semua
DROP POLICY IF EXISTS "follow_ups_delete_policy" ON public.follow_ups;
CREATE POLICY "follow_ups_delete_policy" ON public.follow_ups
    FOR DELETE
    TO authenticated
    USING (
        public.is_user_approved() AND
        (rm_id = auth.uid() OR public.current_user_role() = 'admin')
    );
