-- ==============================================================================
-- MIGRATION 1: Initial Schema for CallPlan (Supabase PostgreSQL)
-- ==============================================================================

-- Enable extensions if needed
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 1. PROFILES TABLE (linked to Supabase auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    nama VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'rm' CHECK (role IN ('rm', 'admin')),
    status VARCHAR(30) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    assigned_area VARCHAR(100) DEFAULT 'Bandung',
    approved_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.profiles IS 'Data profil pengguna, role (rm/admin), dan status approval';
COMMENT ON COLUMN public.profiles.status IS 'Status akun: pending (menunggu verifikasi Admin), approved (aktif), rejected (ditolak)';

-- 2. NASABAHS TABLE (Data Nasabah Prospek & Debitur)
CREATE TABLE IF NOT EXISTS public.nasabahs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by_rm_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    nama VARCHAR(150) NOT NULL,
    alamat TEXT NOT NULL,
    no_hp VARCHAR(30) NOT NULL,
    no_rekening VARCHAR(50),
    kategori VARCHAR(30) NOT NULL DEFAULT 'Prospek' CHECK (kategori IN ('Prospek', 'Debitur')),
    status_pinjaman VARCHAR(50) NOT NULL DEFAULT 'Belum ada pinjaman' 
        CHECK (status_pinjaman IN ('Belum ada pinjaman', 'Dalam pengajuan', 'Aktif', 'Perlu tindak lanjut', 'Lunas')),
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7),
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.nasabahs IS 'Daftar nasabah prospek dan debitur beserta koordinat untuk rute kunjungan';
COMMENT ON COLUMN public.nasabahs.no_rekening IS 'Nomor rekening disimpan sebagai teks agar angka nol di depan tidak hilang';

-- 3. JADWAL KUNJUNGANS TABLE (Call Plan & Log Kunjungan)
CREATE TABLE IF NOT EXISTS public.jadwal_kunjungans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nasabah_id BIGINT NOT NULL REFERENCES public.nasabahs(id) ON DELETE RESTRICT,
    rm_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    tanggal DATE NOT NULL,
    waktu TIME NOT NULL,
    tujuan VARCHAR(120) NOT NULL,
    prioritas VARCHAR(20) NOT NULL DEFAULT 'normal' CHECK (prioritas IN ('normal', 'tinggi')),
    status VARCHAR(30) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'selesai', 'reschedule', 'tidak_ditemui')),
    catatan_hasil TEXT,
    check_in_at TIMESTAMPTZ,
    check_in_latitude NUMERIC(10, 7),
    check_in_longitude NUMERIC(10, 7),
    check_in_accuracy NUMERIC(8, 2),
    check_in_distance_meters NUMERIC(8, 2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

COMMENT ON TABLE public.jadwal_kunjungans IS 'Agenda call plan kunjungan nasabah beserta hasil dan validasi check-in GPS';

-- 4. JADWAL HISTORY TABLE (Audit Trail Perubahan Jadwal & Reschedule)
CREATE TABLE IF NOT EXISTS public.jadwal_history (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    jadwal_id BIGINT NOT NULL REFERENCES public.jadwal_kunjungans(id) ON DELETE CASCADE,
    changed_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    action_type VARCHAR(50) NOT NULL, -- 'status_change', 'reschedule', 'check_in', 'time_update'
    previous_status VARCHAR(30),
    new_status VARCHAR(30),
    previous_date DATE,
    new_date DATE,
    previous_time TIME,
    new_time TIME,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 5. AUDIT LOGS TABLE (Aktivitas Sistem & Keamanan)
CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    action VARCHAR(50) NOT NULL,
    entity_type VARCHAR(50) NOT NULL,
    entity_id TEXT NOT NULL,
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Indexes for optimal performance
CREATE INDEX IF NOT EXISTS idx_profiles_role_status ON public.profiles(role, status);
CREATE INDEX IF NOT EXISTS idx_nasabahs_deleted_at ON public.nasabahs(deleted_at);
CREATE INDEX IF NOT EXISTS idx_nasabahs_kategori ON public.nasabahs(kategori);
CREATE INDEX IF NOT EXISTS idx_nasabahs_created_by ON public.nasabahs(created_by_rm_id);
CREATE INDEX IF NOT EXISTS idx_jadwal_tanggal_status ON public.jadwal_kunjungans(tanggal, status);
CREATE INDEX IF NOT EXISTS idx_jadwal_rm_id ON public.jadwal_kunjungans(rm_id);
CREATE INDEX IF NOT EXISTS idx_jadwal_nasabah_id ON public.jadwal_kunjungans(nasabah_id);
CREATE INDEX IF NOT EXISTS idx_jadwal_history_jadwal_id ON public.jadwal_history(jadwal_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_actor ON public.audit_logs(actor_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON public.audit_logs(created_at DESC);
